# ---------------------------------------------------------------- เสาปูนปั้น (pilaster) ก่ออิฐรอบเสานอก
def pil(id_, cx, cy, d, depth, width, z0, z1, src, st, note, hollow):
    """d = ทิศยื่น (+x/-x/+y/-y) · ยื่นจากผิวผนังนอก (กริด ±0.15) ออกไป depth · hollow = ก่อเป็นกล่องเปลือก 0.10"""
    sx, sy = {'+x': (1, 0), '-x': (-1, 0), '+y': (0, 1), '-y': (0, -1)}[d]
    f0, f1 = 0.15, 0.15 + depth
    def P(u, v):   # u = ตามทิศยื่น, v = ขวาง
        return (cx + sx * u, cy + v) if sx else (cx + v, cy + sy * u)
    hw = width / 2
    ids = []
    if hollow:
        for k, (a, b) in enumerate((((f0, -hw + 0.05), (f1, -hw + 0.05)), ((f0, hw - 0.05), (f1, hw - 0.05)), ((f1 - 0.05, -hw + 0.10), (f1 - 0.05, hw - 0.10))), 1):
            w = seg_wall(f'{id_}-{k}', P(*a), P(*b), z0, z1, src, st, note=note, ext=True); ids.append(w['id'])
    else:
        w = seg_wall(id_, P((f0 + f1) / 2, -hw), P((f0 + f1) / 2, hw), z0, z1, src, st, t=depth, note=note, ext=True); ids.append(w['id'])
    return ids

