def seg_wall(id_, p0, p1, bot, top, src, st=FD, t=0.10, note='', ext=False, kind='brick_mon'):
    w = {'id': id_, 'kind': kind, 't': t, 'path': [[round(p0[0], 3), round(p0[1], 3)], [round(p1[0], 3), round(p1[1], 3)]],
         'bottom': bot, 'top': top, 'status': st, 'src': src}
    if ext: w['exterior'] = True
    if note: w['note'] = note
    walls.append(w); return w

def run(id_, p0, p1, fl, src, ops=(), st=FD, note='', ext=False, split=True):
    """ผนังแนวตรง ตัดเป็นท่อนที่หน้าเสา (เสาที่แนวผนังผ่าน) · ops = [(type, พิกัดกึ่งกลางตามแนว)]"""
    bot, top = (0.85, 4.45) if fl == '1F' else (4.45, 8.85)
    hor = abs(p0[1] - p1[1]) < 1e-6
    a, b = (p0[0], p1[0]) if hor else (p0[1], p1[1])
    c = p0[1] if hor else p0[0]
    cuts = []
    if split:
        for cx, cy in COLS[fl]:
            along, perp = (cx, cy) if hor else (cy, cx)
            if abs(perp - c) <= 0.16 and min(a, b) - 0.14 < along < max(a, b) + 0.14:
                cuts.append((along - 0.15, along + 0.15))
    lo, hi = min(a, b), max(a, b)
    pieces, cur = [], lo
    for c0, c1 in sorted(cuts):
        if c0 > cur + 0.01:
            pieces.append((cur, min(c0, hi)))
        cur = max(cur, c1)
    if cur < hi - 0.01:
        pieces.append((cur, hi))
    out = []
    for k, (u0, u1) in enumerate(pieces, 1):
        wid = id_ if len(pieces) == 1 else f'{id_}{"abcdefghijk"[k - 1]}'
        q0 = (u0, c) if hor else (c, u0); q1 = (u1, c) if hor else (c, u1)
        w = seg_wall(wid, q0, q1, bot, top, src, st, note=note, ext=ext)
        n = 0
        for typ, at in ops:
            if u0 - 1e-6 <= at <= u1 + 1e-6:
                n += 1
                opens.append({'id': f'{wid}-{typ}{n}', 'type': typ, 'wall': wid, 'at': round(at - u0, 3), 'status': FD if typ[:2] in ('AW', 'AD') else AS,
                              'src': src + ' (บล็อก ' + typ + ')'})
                tw = OT[typ]['w']
                if at - tw / 2 < u0 - 0.02 or at + tw / 2 > u1 + 0.02:
                    print('!! ช่องเปิดเกินท่อนผนัง', wid, typ, at, u0, u1)
        out.append(wid)
    return out

