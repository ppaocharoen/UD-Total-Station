# Step 4 วัสดุ/ผิว — ห้องน้ำ ท12 (ต่อจาก Step 3) · ส่วนที่ 1: พื้น รางน้ำ ฝ้า เชิงชาย/ครอบหลังคา
# แผ่น: A.2.01 รายการวัสดุพื้น F1–F3 / ฝ้า CL1 + ป้ายห้อง · A.2.02 แปลนหลังคา · A.4.01–A.4.06 รูปตัด (CL1 ใต้จันทัน + ใต้ชายคา · แบบขยายรางตื้น)
import json, math, datetime
FD, AS, US = 'from_drawing', 'assumed', 'user'
m = json.load(open('../s3/stage3.bm.json'))
F = m['finishes'] = [f for f in m.get('finishes', []) if False]
rows = []
def row(cat, id_, desc, src, st=FD, note=''): rows.append((cat, id_, desc, src, st, note))
SL = {s['id']: s for s in m['slabs']}
def area(P): return abs(sum(P[i][0] * P[(i + 1) % len(P)][1] - P[(i + 1) % len(P)][0] * P[i][1] for i in range(len(P)))) / 2

# ---------------------------------------------------------------- พื้น (A.2.01 รายการวัสดุพื้น)
SPEC = {'F1': 'พื้นคอนกรีตผิวขัดหยาบ', 'F2': 'พื้นปูกระเบื้องแกรนิตโต้ผิวหยาบ', 'F3': 'พื้นผิวทรายล้าง'}
ROOM = {'S-WCM': 'ห้องน้ำชาย', 'S-WCM-S': 'ห้องน้ำชาย (ห้องส้วม)', 'S-WCF': 'ห้องน้ำหญิง', 'S-WCF-S': 'ห้องน้ำหญิง (ห้องส้วม)', 'S-DIS': 'ห้องน้ำคนพิการ',
        'S-ENT': 'ทางเข้า', 'S-RAMP': 'ทางลาด', 'S-LAND': 'ชานพักทางลาด'}
FL = [('S-WCM', 'F2'), ('S-WCM-S', 'F2'), ('S-WCF', 'F2'), ('S-WCF-S', 'F2'), ('S-DIS', 'F2'), ('S-ENT', 'F2'), ('S-RAMP', 'F3'), ('S-LAND', 'F3')] + \
     [(k, 'F1') for k in SL if k.startswith('S-WK')]
tot = {}
for sid, fm in FL:
    s = SL[sid]; room = ROOM.get(sid, 'ทางเดินรอบอาคาร')
    f = {'id': 'FF-' + sid[2:], 'kind': 'floor', 'spec': SPEC[fm], 'status': FD, 'src': f'A.2.01 รายการวัสดุพื้น {fm} (ป้ายห้อง {room})', 'polygon': s['polygon'],
         'z': s['top'], 'level': s.get('level', '1F'), 'room': room, 'note': f'{fm} · ขอบถึงศูนย์ผนังตามผืนพื้นโครงสร้าง {sid}'}
    if s.get('ramp'):
        L = 2.40; f['qty'] = round(area(s['polygon']) * math.hypot(1, 0.20 / L), 3); f['unit'] = 'ตร.ม.'; f['note'] += ' · พื้นที่ตามแนวลาด 1:12'
    F.append(f); tot[fm] = tot.get(fm, 0) + (f.get('qty') or area(s['polygon']))
for fm in ('F2', 'F3', 'F1'):
    row('พื้น', f'FF-… ({fm})', f'{SPEC[fm]} รวม {tot[fm]:.2f} ตร.ม.', 'A.2.01')
# ---------------------------------------------------------------- รางน้ำหน้าห้องส้วม (แบบขยายรางตื้น A.4.01)
GL = {'S-GUT-M': 3.15, 'S-GUT-F': 5.25}
Lg = sum(GL.values())
F.append({'id': 'CH-01', 'kind': 'other', 'spec': 'รางตื้น คสล. กว้าง 0.15 ม. ลึก 0.06 ม. ปูกระเบื้องแกรนิตโต้ผิวหยาบ', 'status': FD,
          'src': 'A.4.01 แบบขยายรูปตัดรางตื้น + A.2.01 (ชั้น WC-OUTL)', 'qty': round(Lg, 2), 'unit': 'ม.', 'room': 'ห้องน้ำชาย / ห้องน้ำหญิง',
          'note': f'S-GUT-M ยาว 3.15 + S-GUT-F ยาว 5.25 · ผิวกระเบื้อง ก้น 0.15 + ข้าง 2×0.06 = 0.27 ตร.ม./ม. ({Lg * 0.27:.2f} ตร.ม.) · แนวท่อระบายน้ำพร้อมตะแกรงดักกลิ่น = Step 5'})
F.append({'id': 'CH-02', 'kind': 'other', 'spec': 'ขอบคิ้วอลูมิเนียมรางตื้น', 'status': FD, 'src': 'A.4.01 แบบขยายรูปตัดรางตื้น', 'qty': round(2 * Lg, 2), 'unit': 'ม.',
          'note': 'ขอบรางสองข้าง'})
row('พื้น', 'CH-01 / CH-02', f'รางตื้น คสล. กว้าง 0.15 ลึก 0.06 ปูแกรนิตโต้ยาว {Lg:.2f} ม. · คิ้วอลูมิเนียมขอบราง {2 * Lg:.2f} ม.', 'A.4.01')

# ---------------------------------------------------------------- ฝ้า CL1 (A.2.01 รายการวัสดุฝ้า + รูปตัด: ติดใต้จันทัน ทั้งในอาคารและใต้ชายคา)
P0, DZ = 3.70, -0.40 / 5.80   # ระนาบโครง (ท้องจันทัน) ที่ y = 0 · ลาดลงทาง +Y
kf = math.hypot(1, DZ)
CL_SPEC = 'ฝ้าสมาร์ทบอร์ด หนา 6 มม. ฉาบเรียบรอยต่อทาสี โครงคร่าว C-Line @0.40 ม. เว้นรอยต่อยาแนวด้วยซิลิโคน'
IN = [[-0.05, -0.05, 10.85, 5.85]]
EV = [[-1.10, -1.10, 11.90, -0.05], [-1.10, 5.85, 11.90, 6.90], [-1.10, -0.05, -0.05, 5.85], [10.85, -0.05, 11.90, 5.85]]
ra = lambda R: sum(abs(r[2] - r[0]) * abs(r[3] - r[1]) for r in R)
slope = {'axis': 'Y', 'at': 0.0, 'z': P0, 'dz': round(DZ, 5)}
F.append({'id': 'CL1', 'kind': 'ceiling', 'spec': CL_SPEC + ' ติดตั้งระดับท้องจันทันเหล็ก', 'status': FD, 'src': 'A.2.01 รายการวัสดุฝ้า CL1 + รูปตัด A.4.01–A.4.06',
          'rects': IN, 'z': P0, 'slope': slope, 'qty': round(ra(IN) * kf, 3), 'unit': 'ตร.ม.', 'room': 'ในอาคาร',
          'note': f'ฝ้าเอียงตามท้องจันทัน +3.70 (แนว A) → +3.30 (แนว C) · ขอบถึงศูนย์ผนังรอบอาคาร · พื้นที่ตามแนวเอียง ×{kf:.4f}'})
F.append({'id': 'CL1-E', 'kind': 'ceiling', 'spec': 'ฝ้าชายคา ' + CL_SPEC + ' ติดตั้งระดับท้องจันทันเหล็ก', 'status': FD, 'src': 'รูปตัด A.4.01–A.4.06 (CL1 ใต้ชายคา)',
          'rects': EV, 'z': P0, 'slope': slope, 'qty': round(ra(EV) * kf, 3), 'unit': 'ตร.ม.', 'room': 'ชายคา',
          'note': 'ใต้ชายคารอบอาคารยื่น 1.10 ถึงหลังเชิงชาย · พื้นที่ตามแนวเอียง'})
row('ฝ้า', 'CL1', f'ฝ้าสมาร์ทบอร์ด 6 มม. ในอาคาร (เอียงตามท้องจันทัน +3.70→+3.30) {ra(IN) * kf:.2f} ตร.ม.', 'A.2.01, A.4.x')
row('ฝ้า', 'CL1-E', f'ฝ้าชายคา สมาร์ทบอร์ด 6 มม. รอบอาคาร ยื่น 1.10 {ra(EV) * kf:.2f} ตร.ม.', 'A.4.x')

# ---------------------------------------------------------------- เชิงชาย / ครอบหลังคา (A.4.01 + A.2.02)
Lx, Ly = 13.00, 8.00
F.append({'id': 'RF-FA', 'kind': 'other', 'spec': 'เชิงชายสำเร็จรูป ขนาด 8"', 'status': FD, 'src': 'รูปตัด A.4.01–A.4.06 (เชิงชายปลายจันทันทั้งสองด้าน)', 'qty': round(2 * Lx, 2), 'unit': 'ม.',
          'note': 'ปลายจันทันด้านสูง (แนว A) และด้านต่ำ (แนว C) ยาวด้านละ 13.00'})
F.append({'id': 'RF-CAP', 'kind': 'other', 'spec': 'ครอบหลังคาเมทัลชีท', 'status': AS, 'src': 'A.2.02 แปลนหลังคา + รูปตัด A.4.01', 'qty': round(Lx + 2 * Ly * kf, 2), 'unit': 'ม.',
          'note': '**ถาม:** ครอบด้านสูง (แนว A) 13.00 + ครอบข้างจั่ว 2 ด้าน (กริด 1 / 4) ยาวตามลาด 8.02 — แปลนหลังคาชี้ที่ขอบข้าง รูปตัดชี้ที่ด้านสูง'})
row('หลังคา', 'RF-FA', f'เชิงชายสำเร็จรูป 8" ยาว {2 * Lx:.2f} ม. (ปลายจันทันสองด้าน)', 'A.4.x')
row('หลังคา', 'RF-CAP', f'ครอบหลังคาเมทัลชีท {Lx + 2 * Ly * kf:.2f} ม. (ด้านสูง + ข้างจั่ว 2 ด้าน)', 'A.2.02, A.4.01', AS, 'ถาม Earth')

m['meta']['name'] = 'ห้องน้ำ ท12 — Step 4 วัสดุ/ผิว (ส่วนที่ 1)'; m['meta']['stage'] = 4
m['history'].append({'at': datetime.datetime.now().astimezone().isoformat(timespec='seconds'), 'by': 'claude (อ่านแบบ Step 4)', 'sections': ['finishes'],
                     'note': 'Step 4 ส่วนที่ 1: พื้น F1–F3 รางตื้น ฝ้า CL1 เชิงชาย ครอบหลังคา'})
json.dump(m, open('stage4.bm.json', 'w'), ensure_ascii=False, indent=1)
json.dump(rows, open('stage4_rows.json', 'w'), ensure_ascii=False, indent=1)
print('finishes', len(F), {k: round(v, 2) for k, v in tot.items()}, 'CL1', round(ra(IN) * kf, 2), 'CL1-E', round(ra(EV) * kf, 2))
